def _fence(reference,carry,*,create=False):
    """Original permanent two-lock/two-receipt amendment claim protocol."""
    binding,auth,_=context(reference,window=create)
    predecessor_root=Path(carry['lineage'][-1]['root'])
    need(binding['claim_parent']==str(predecessor_root.parent))
    parent=launch._dir(predecessor_root.parent,False); folder=lock=None
    def action():
        if create: _clock(reference)
    try:
        if create:
            try: action(); os.mkdir('campaign-successor-claims',0o700,dir_fd=parent); os.fsync(parent)
            except FileExistsError: pass
        folder=os.open('campaign-successor-claims',os.O_RDONLY|os.O_DIRECTORY|os.O_NOFOLLOW,dir_fd=parent)
        info=os.fstat(folder); need(info.st_uid==os.getuid() and stat.S_IMODE(info.st_mode)==0o700)
        name=launch._digest({'root':str(predecessor_root),'qualification_id':carry['qualification_id']})
        authname='amendment-'+auth['authorization_id']
        action(); lock=launch._file(folder,name+'.lock',os.O_RDWR|(os.O_CREAT|os.O_EXCL if create else 0))
        fcntl.flock(lock,fcntl.LOCK_EX|fcntl.LOCK_NB); action()
        expected={'schema':1,'document_type':'qualification_matrix_amendment_claim','amendment':reference,
            'prior_root':str(predecessor_root),'prior_qualification_id':carry['qualification_id'],'final_root':str(FINAL_ROOT)}
        if create:
            action(); os.fsync(lock); os.fsync(folder)
            fd=launch._file(folder,authname+'.lock',os.O_RDWR|os.O_CREAT|os.O_EXCL)
            try: action(); os.fsync(fd)
            finally: os.close(fd)
            for filename in (name+'.json',authname+'.json'):
                action(); fd=launch._file(folder,filename,os.O_WRONLY|os.O_CREAT|os.O_EXCL)
                with os.fdopen(fd,'wb') as stream:
                    action(); stream.write(launch._json(expected)); stream.flush(); action(); os.fsync(stream.fileno())
                os.fsync(folder)
        fd=launch._file(folder,authname+'.lock',os.O_RDWR); os.close(fd)
        need(launch._read(folder,name+'.json')==expected and launch._read(folder,authname+'.json')==expected)
    finally:
        if lock is not None: os.close(lock)
        if folder is not None: os.close(folder)
        os.close(parent)


