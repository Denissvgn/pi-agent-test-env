@contextlib.contextmanager
def intent_mirrors(registry,manifest,gate):
    """Source-owned per-instance pre-write metadata; no class/global patch.

    The first original Registry write publishes the same immutable intent SHA
    used by LaunchLedger. Updates (including cleanup) always call the original
    bound method with the identical object; no work-clock gate is added there.
    A failed mirror publication prevents its first canonical write/delegate.
    """
    original=registry.write; existed='write' in registry.__dict__
    previous=registry.__dict__.get('write'); seen=set()
    def write(record):
        identifier=record.get('launch_id') if type(record) is dict else None
        if identifier not in gate.expected and identifier not in seen:
            reference=manifest['campaign_amendment']; _clock(reference)
            launch._uuid(identifier); need(len(seen)<EXTRA_REGISTRY_SLOTS)
            need(record.get('status')=='intent')
            need(record.get('registry')==registry.registry_id and record.get('generation')==registry.generation)
            need(record.get('daemon')==registry.daemon)
            kind=record.get('kind','container'); need(kind in ('container','network'))
            if kind=='network':
                need(record.get('runroot') is None and record.get('image') is None and record.get('mounts')==[])
            else:
                need(record.get('owner_pid')==os.getpid())
                need(Path(record['runroot']).is_relative_to(FINAL_ROOT))
            body={'schema':1,'launch_id':identifier,'kind':kind,
                'intent_sha256':launch._intent_identity(record),'before_original_Registry_write':True,
                'registry':record['registry'],'generation':record['generation'],'daemon':record['daemon'],
                'runroot':record.get('runroot'),'qualification_id':manifest['qualification_id'],
                'source_scope_root':str(FINAL_ROOT)}
            folder=launch._dir(FINAL_ROOT)
            try:
                _clock(reference)
                fd=launch._file(folder,'intent-'+identifier+'.json',os.O_WRONLY|os.O_CREAT|os.O_EXCL)
                with os.fdopen(fd,'wb') as stream:
                    _clock(reference); stream.write(launch._json(body)); stream.flush()
                    _clock(reference); os.fsync(stream.fileno())
                _clock(reference); os.fsync(folder)
            finally: os.close(folder)
            seen.add(identifier)
        return original(record)
    registry.write=write
    try: yield
    finally:
        if existed: registry.write=previous
        else: del registry.__dict__['write']


def admission_factory(original,manifest):
    """Two qualifier callsites wrap their captured original SDK contextmanager.

    This hook is BEFORE original Registry construction/reconcile. It never
    replaces either operation and does not alter pi_lab/resources globals.
    """
    need(callable(original))
    reference=manifest['campaign_amendment']
    @contextlib.contextmanager
    def held(path,wait_seconds=0):
        binding,_,_=context(reference,window=True,stage='execute')
        need(str(Path(path).absolute())==binding['original_lock'])
        replay.same_typed(wait_seconds,30)
        seal=bound('execute'); policy=public(binding['sdk_policy'],seal=seal)
        import application_sdk_admission
        import resources
        need(original is resources.admission_lock)
        captured={}
        def before_registry(*,lease_fd,lock_path,registry_root):
            need(not captured)
            _,_,bounds=context(reference,window=True,stage='execute')
            entry=time.monotonic(); wallentry=time.time()
            current_policy=copy.deepcopy(policy)
            current_policy['admission_budget']={'started_monotonic':entry,'started_wall':wallentry,
                'deadline_monotonic':min(entry+120,bounds['deadline_monotonic']-30),
                'deadline_wall':min(wallentry+120,bounds['deadline_wall']-30)}
            extended=application_sdk_admission.extend_current_scope_policy(current_policy,
                lease_fd=lease_fd,lock_path=lock_path,registry_root=registry_root,
                manifest=_policy(manifest,reference),ledger_root=FINAL_ROOT/'launch-ledger',scope_root=FINAL_ROOT)
            gate=application_sdk_admission.AdmissionGate(extended)
            gate(lease_fd=lease_fd,lock_path=lock_path,registry_root=registry_root)
            captured['gate']=gate
        with original(path,wait_seconds,before_registry=before_registry) as registry:
            need(set(captured)=={'gate'})
            gate=captured['gate']; gate.assert_after_yield(registry)
            need(registry.lease_fd is not None)
            token=_ACTUAL_ADMISSION.set((registry,gate,reference,registry.lease_fd,copy.deepcopy(gate.expected),copy.deepcopy(gate.witness)))
            try:
                with intent_mirrors(registry,manifest,gate): yield registry
            finally: _ACTUAL_ADMISSION.reset(token)
    return held


def validate_native_dispatch(registry,guard,record=None):
    """Fresh canonical baseline and own delta under actual normal SDK lease.

    Call only AFTER original resources.admission_lock/reconcile yielded CURRENT.
    A stale metadata proof, manual flock or summary cannot supply this state.
    Original LaunchGuard remains responsible for exact argv/mount/CID/resources.
    No constructor/reconcile, record mutation or Docker command occurs here.
    """
    reference=guard.ledger.manifest['campaign_amendment']; binding,_,_=context(reference,window=True,stage='execute')
    _decision(binding)
    import ownership_registry as registry_api
    admitted=_ACTUAL_ADMISSION.get()
    need(admitted is not None and admitted[0] is registry and admitted[2]==reference)
    need(admitted[3]==registry.lease_fd and registry_api.CURRENT.get() is registry)
    need(type(registry.lease_fd) is int and registry.lease_fd>=0)
    lockpath=Path(binding['original_lock']); held=os.fstat(registry.lease_fd)
    parent=launch._dir(lockpath.parent,False)
    try: named=os.stat(lockpath.name,dir_fd=parent,follow_symlinks=False)
    finally: os.close(parent)
    need(stat.S_ISREG(held.st_mode) and held.st_uid==os.getuid() and held.st_nlink==1)
    need(stat.S_IMODE(held.st_mode)==0o600 and (held.st_dev,held.st_ino)==(named.st_dev,named.st_ino))
    need([held.st_dev,held.st_ino]==binding['original_lock_identity'])
    import application_sdk_admission
    need(type(admitted[1]) is application_sdk_admission.AdmissionGate)
    witness=admitted[5]
    need(witness['lease_fd']==registry.lease_fd and [witness['lease_device'],witness['lease_inode']]==[held.st_dev,held.st_ino])
    need(witness['registry_root']==str(registry.root))
    records=registry.load(); current={r['launch_id']:r for r in records}
    need(len(current)==len(records) and len(current)<=registry_api.MAX_RECORDS)
    old=admitted[4]; need(type(old) is dict and len(old)>=6774)
    need(len(old)+EXTRA_REGISTRY_SLOTS<=registry_api.MAX_RECORDS)
    need(set(old)<=set(current))
    for key,digest in old.items():
        need(current[key]['status']=='released' and launch._digest(current[key])==digest)
    own=[r for k,r in current.items() if k not in old]
    need(len(own)<=EXTRA_REGISTRY_SLOTS)
    need(Path(registry.runroot).is_relative_to(FINAL_ROOT))
    for row in own:
        need(row['registry']==registry.registry_id and row['generation']==registry.generation and row['daemon']==registry.daemon)
        if row.get('kind','container')=='network':
            need(row['container'] in guard._networks and launch._intent_identity(row)==launch._intent_identity(guard._networks[row['container']]))
            need(row['image'] is None and row['mounts']==[])
        else:
            need(row.get('owner_pid')==os.getpid() and Path(row['runroot']).is_relative_to(FINAL_ROOT))
    if record is not None: need(record['launch_id'] in current and record['launch_id'] not in old)
    # Refence the original named inode after the full inventory read.
    parent=launch._dir(lockpath.parent,False)
    try: after=os.stat(lockpath.name,dir_fd=parent,follow_symlinks=False)
    finally: os.close(parent)
    need((held.st_dev,held.st_ino)==(after.st_dev,after.st_ino)); _clock(reference)
    return {'historical_records':len(old),'own_current_records':len(own),'actual_lease_fenced':True}
